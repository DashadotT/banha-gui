static void update_status_colors() {

  const char *tempStatus = get_var_temp_status();
  const char *noiseStatus = get_var_noise_status();

  // =====================================================
  // TEMPERATURE
  // =====================================================

  if (tempStatus != NULL) {

    lv_color_t color;

    if (strcmp(tempStatus, "NORMAL") == 0) {
      color = lv_color_hex(0x00BF63);  // Green

    } else if (strcmp(tempStatus, "MODERATE") == 0) {
      color = lv_color_hex(0xEBAF1C);  // Yellow

    } else {
      color = lv_color_hex(0xFF383C);  // Red
    }

    // Main page
    lv_obj_set_style_text_color(
      objects.temp_status_label,
      color,
      LV_PART_MAIN
    );

    // Recording page
    lv_obj_set_style_text_color(
      objects.rec_temp_status,
      color,
      LV_PART_MAIN
    );
  }

  // =====================================================
  // NOISE
  // =====================================================

  if (noiseStatus != NULL) {

    lv_color_t color;

    if (strcmp(noiseStatus, "NORMAL") == 0) {
      color = lv_color_hex(0x00BF63);  // Green

    } else if (strcmp(noiseStatus, "MODERATE") == 0) {
      color = lv_color_hex(0xEBAF1C);  // Yellow

    } else {
      color = lv_color_hex(0xFF383C);  // Red
    }

    // Main page
    lv_obj_set_style_text_color(
      objects.noise_status_label,
      color,
      LV_PART_MAIN
    );

    // Recording page
    lv_obj_set_style_text_color(
      objects.rec_noise_status,
      color,
      LV_PART_MAIN
    );
  }
}

